type LocaleContextValue = {
  language: Language
  direction: 'ltr' | 'rtl'
  setLanguage: (language: Language) => void
  t: (text: string) => string
}

const LocaleContext = createContext<LocaleContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const stored = localStorage.getItem('kindergarten-language')
    return stored === 'ar' ? 'ar' : 'en'
  })

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
    localStorage.setItem('kindergarten-language', language)
  }, [language])

  const value = useMemo<LocaleContextValue>(() => ({
    language,
    direction: language === 'ar' ? 'rtl' : 'ltr',
    setLanguage: setLanguageState,
    t: (text) => translations[language][text] ?? text,
  }), [language])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  const value = useContext(LocaleContext)
  if (!value) throw new Error('useLocale must be used within LanguageProvider')
  return value
}

export function LanguageToggle() {
  const { language, setLanguage } = useLocale()
  return (
    <button
      type="button"
      className="workspace-language-toggle"
      aria-label={language === 'en' ? 'Switch to Arabic' : 'Switch to English'}
      onClick={() => setLanguage(language === 'en' ? 'ar' : 'en')}
    >
      {language === 'en' ? 'العربية' : 'English'}
    </button>
  )
}
